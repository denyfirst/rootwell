import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { createPrivateKey } from "node:crypto";
import fs from "node:fs";
import vm from "node:vm";

const [wasmPath, runtimePath] = process.argv.slice(2);
if (!wasmPath || !runtimePath) throw new Error("usage: node test-browser-pfx.mjs <wasm> <wasm_exec.js>");
vm.runInThisContext(fs.readFileSync(runtimePath, "utf8"), { filename: runtimePath });
let ready;
const signal = new Promise(resolve => { ready = resolve; });
globalThis.rootwellWasmReady = ready;
const go = new Go();
const module = await WebAssembly.instantiate(fs.readFileSync(wasmPath), go.importObject);
go.run(module.instance);
await Promise.race([signal, new Promise((_, reject) => setTimeout(() => reject(new Error("PFX WASM timeout")), 10000))]);
assert.equal(typeof rootwellPFXInspect, "function");
assert.equal(typeof rootwellPFXOutput, "function");
const fixture = JSON.parse(execFileSync("go", ["run", "./scripts/generate-browser-pfx-fixture.go"], { encoding: "utf8" }));
const certificate = Uint8Array.from(Buffer.from(fixture.certificate, "base64"));
const key = Uint8Array.from(Buffer.from(fixture.key, "base64"));
const sourcePFX = Uint8Array.from(Buffer.from(fixture.pfx, "base64"));
const password = new TextEncoder().encode(fixture.password);
const empty = new Uint8Array();
const summary = JSON.parse(rootwellPFXInspect(sourcePFX, password));
assert.equal(summary.ok, true);
assert.equal(summary.result.certificates.length, 1);
assert.equal(summary.result.certificates[0].matching_key, true);
const fingerprint = summary.result.certificates[0].fingerprint;
const revealed = rootwellPFXOutput("reveal", sourcePFX, empty, empty, password, empty, fingerprint);
assert.equal(revealed.ok, true);
assert.equal(revealed.result.filename, "");
assert.equal(revealed.result.format, "pkcs8-pem");
assert.equal(createPrivateKey(Buffer.from(revealed.result.bytes)).asymmetricKeyType, "ec");
assert.equal(rootwellPFXOutput("reveal", sourcePFX, empty, empty, new TextEncoder().encode("wrong"), empty, fingerprint).ok, false);
assert.equal(rootwellPFXOutput("reveal", sourcePFX, empty, empty, password, empty, "AA:".repeat(31) + "AA").ok, false);
assert.equal(rootwellPFXOutput("reveal", sourcePFX, empty, empty, password, password, fingerprint).ok, false);
revealed.result.bytes.fill(0);
assert.match(fingerprint, /^(?:[0-9A-F]{2}:){31}[0-9A-F]{2}$/);
assert.equal(JSON.parse(rootwellPFXInspect(sourcePFX, new TextEncoder().encode("wrong-password"))).ok, false);
const tampered = sourcePFX.slice();
tampered[tampered.length - 8] ^= 1;
assert.equal(JSON.parse(rootwellPFXInspect(tampered, password)).ok, false);
const exportedCert = rootwellPFXOutput("certificate", sourcePFX, empty, empty, password, empty, fingerprint + ":pem");
assert.equal(exportedCert.ok, true);
assert.deepEqual(Buffer.from(exportedCert.result.bytes), Buffer.from(certificate));
const newKeyPassword = new TextEncoder().encode("separate-browser-key-password-2026");
const exportedKey = rootwellPFXOutput("key", sourcePFX, empty, empty, password, newKeyPassword, fingerprint);
assert.equal(exportedKey.ok, true);
assert.equal(createPrivateKey({ key: Buffer.from(exportedKey.result.bytes), passphrase: Buffer.from(newKeyPassword) }).asymmetricKeyType, "ec");
assert.equal(rootwellPFXOutput("key", sourcePFX, empty, empty, password, newKeyPassword, "AA:".repeat(31) + "AA").ok, false);
assert.equal(rootwellPFXOutput("key", sourcePFX, empty, empty, new TextEncoder().encode("wrong-password"), newKeyPassword, fingerprint).ok, false);
const created = rootwellPFXOutput("create", certificate, key, empty, password, empty, "");
assert.equal(created.ok, true);
assert.equal(JSON.parse(rootwellPFXInspect(created.result.bytes, password)).result.certificates[0].fingerprint, fingerprint);
// Node's OpenSSL-backed encoder provides an independent encrypted input.
const inputPassword = new TextEncoder().encode("separate-synthetic-input-key-password-2026");
const encryptedInput = Uint8Array.from(Buffer.from(createPrivateKey(Buffer.from(key)).export({
  type: "pkcs8", format: "pem", cipher: "aes-256-cbc", passphrase: Buffer.from(inputPassword)
})));
const encryptedCreated = rootwellPFXOutput("create", certificate, encryptedInput, empty, password, inputPassword, "");
assert.equal(encryptedCreated.ok, true, "OpenSSL-backed encrypted PKCS#8 input failed");
assert.equal(JSON.parse(rootwellPFXInspect(encryptedCreated.result.bytes, password)).result.certificates[0].fingerprint, fingerprint);
assert.equal(JSON.parse(rootwellPFXInspect(encryptedCreated.result.bytes, inputPassword)).ok, false);
assert.equal(rootwellPFXOutput("create", certificate, encryptedInput, empty, password, empty, "").ok, false);
assert.equal(rootwellPFXOutput("create", certificate, encryptedInput, empty, password, new TextEncoder().encode("wrong"), "").ok, false);
assert.equal(rootwellPFXOutput("create", certificate, encryptedInput, empty, inputPassword, inputPassword, "").ok, false);
assert.equal(rootwellPFXOutput("create", certificate, key, empty, password, inputPassword, "").ok, false);
assert.equal(rootwellPFXOutput("create", certificate, encryptedInput, empty, password, new Uint8Array(257), "").ok, false);
assert.equal(rootwellPFXOutput("create", certificate, new TextEncoder().encode("not a key"), empty, password, empty, "").ok, false);
assert.equal(rootwellPFXOutput("create", certificate, key, empty, new TextEncoder().encode("short"), empty, "").ok, false);
assert.equal(rootwellPFXOutput("certificate", sourcePFX, empty, empty, password, empty, fingerprint + ":garbage").ok, false);
for (const item of [certificate, key, sourcePFX, password, newKeyPassword, tampered, inputPassword, encryptedInput,
  exportedCert.result.bytes, exportedKey.result.bytes, created.result.bytes, encryptedCreated.result.bytes]) item.fill(0);
console.log("Browser PFX WASM creation, inspection, authenticated extraction, mismatch and refusal passed.");
